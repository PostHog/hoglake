package com.posthog.hoglake.compaction

import com.fasterxml.jackson.module.kotlin.readValue
import com.posthog.hoglake.model.ColType
import com.posthog.hoglake.model.Column
import com.posthog.hoglake.model.ColumnDef
import com.posthog.hoglake.wireObjectMapper
import org.apache.parquet.example.data.Group
import org.apache.parquet.example.data.simple.convert.GroupRecordConverter
import org.apache.parquet.hadoop.ParquetFileReader
import org.apache.parquet.io.ColumnIOFactory
import org.apache.parquet.io.LocalInputFile
import org.apache.parquet.schema.MessageType
import org.apache.parquet.schema.PrimitiveType
import java.nio.file.Files
import java.nio.file.Path
import java.util.HexFormat

/**
 * The VARIANT compaction fixtures pyhoglake wrote
 * (src/test/resources/variant/passthrough, regenerated by
 * pyhoglake/tests/data/variant/regen_passthrough_fixtures.py), and the
 * row-by-row comparison the tests over them share: every surviving
 * row's `metadata`, `value` and `typed_value` leaves, with which of them
 * are present, rendered as text two rows share only when they are byte
 * for byte the same.
 */
object VariantFixtures {
    /** `columns.json`: the table the fixtures were written for — id, then props, rich and raw. */
    val live: List<Column> by lazy { columns("columns.json") }

    /** `other.json`: the same table with `props` under the declaration `mismatch`, `other_a` and `other_b` were written to. */
    val other: List<Column> by lazy { columns("other.json") }

    fun path(name: String): Path =
        Path.of(
            VariantFixtures::class.java.getResource("/variant/passthrough/$name.parquet")!!.toURI(),
        )

    fun bytes(name: String): ByteArray = Files.readAllBytes(path(name))

    /** An input as [expected] reads it: positional ids from [start], [deleted] positions skipped. */
    class Source(val path: Path, val start: Long, val deleted: Set<Long> = emptySet())

    /** Row id -> column name -> [render] of it, over the surviving rows of [inputs]. */
    fun expected(vararg inputs: Source): Map<Long, Map<String, String>> =
        inputs.flatMap { input ->
            read(input.path).second.withIndex()
                .filter { (position, _) -> position.toLong() !in input.deleted }
                .map { (position, row) -> input.start + position to columns(row) }
        }.toMap()

    /** Row id -> column name -> [render] of it, over an output, ids from its carrier. */
    fun rows(path: Path): Map<Long, Map<String, String>> =
        read(path).second.associate { it.getLong(ParquetRewriter.ROW_ID_COLUMN, 0) to columns(it) }

    fun columns(row: Group): Map<String, String> =
        live.associate { column -> column.def.name to render(row, row.type.getFieldIndex(column.def.name)) }

    /**
     * One field of [group] as text that two groups share only when every
     * repetition, every nested field's name and presence, and every leaf's
     * bytes are equal: `[]` for an absent field, `[{a=[..] b=[..]}]` for a
     * group, hex for a binary, raw bits for a float.
     */
    fun render(
        group: Group,
        field: Int,
    ): String {
        val type = group.type.getType(field)
        return (0 until group.getFieldRepetitionCount(field)).joinToString(",", "[", "]") { i ->
            if (type.isPrimitive) {
                when (type.asPrimitiveType().primitiveTypeName) {
                    PrimitiveType.PrimitiveTypeName.INT32 -> group.getInteger(field, i).toString()
                    PrimitiveType.PrimitiveTypeName.INT64 -> group.getLong(field, i).toString()
                    PrimitiveType.PrimitiveTypeName.BOOLEAN -> group.getBoolean(field, i).toString()
                    PrimitiveType.PrimitiveTypeName.FLOAT -> group.getFloat(field, i).toRawBits().toString()
                    PrimitiveType.PrimitiveTypeName.DOUBLE -> group.getDouble(field, i).toRawBits().toString()
                    else -> HexFormat.of().formatHex(group.getBinary(field, i).bytes)
                }
            } else {
                val child = group.getGroup(field, i)
                (0 until child.type.fieldCount).joinToString(
                    " ",
                    "{",
                    "}",
                ) { "${child.type.getFieldName(it)}=${render(child, it)}" }
            }
        }
    }

    fun read(path: Path): Pair<MessageType, List<Group>> =
        ParquetFileReader.open(LocalInputFile(path)).use { reader ->
            val schema = reader.footer.fileMetaData.schema
            val io = ColumnIOFactory().getColumnIO(schema)
            val rows = mutableListOf<Group>()
            while (true) {
                val pages = reader.readNextRowGroup() ?: break
                val records = io.getRecordReader(pages, GroupRecordConverter(schema))
                repeat(Math.toIntExact(pages.rowCount)) { rows += records.read() }
            }
            schema to rows
        }

    /** The column wire of a fixture JSON as catalog [Column]s. */
    private fun columns(resource: String): List<Column> =
        wireObjectMapper()
            .readValue<List<Map<String, Any?>>>(
                Files.readAllBytes(
                    Path.of(VariantFixtures::class.java.getResource("/variant/passthrough/$resource")!!.toURI()),
                ),
            )
            .map {
                @Suppress("UNCHECKED_CAST")
                val params = it["type_params"] as Map<String, Any?>?
                Column(
                    (it["field_id"] as Number).toLong(),
                    it["ordinal"] as Int,
                    ColumnDef(
                        it["name"] as String,
                        ColType.fromWire(it["type"] as String),
                        params,
                        it["nullable"] as Boolean? ?: true,
                    ),
                )
            }
}
