    private fun sign(
        header: JsonNode,
        claims: JsonNode,
    ): String {
        val input =
            b64.encodeToString(mapper.writeValueAsBytes(header)) + "." +
                b64.encodeToString(mapper.writeValueAsBytes(claims))
        val bytes = input.toByteArray(Charsets.US_ASCII)
        val sig =
            Signature.getInstance("SHA256withECDSAinP1363Format").run {
                initSign(privateKey)
                update(bytes)
                sign()
            }
        val ok =
            Signature.getInstance("SHA256withECDSAinP1363Format").run {
                initVerify(publicKey)
                update(bytes)
                verify(sig)
            }
        check(ok) { "the contract key's d does not match its published x/y" }
        return input + "." + b64.encodeToString(sig)
    }
