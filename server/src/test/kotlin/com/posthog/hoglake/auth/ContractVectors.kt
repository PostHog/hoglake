/**
 * The generator of `oauth/contract-vectors.json`: the token contract hoglake
 * verifies, written down as signed examples.
 *
 * hoglake OWNS this file. It is generated here, from this object, and every
 * issuer conforms to it: an issuer's own suite mints each vector's
 * `client`/`operator` input and compares header and claims with the file,
 * and hoglake's suite ([ContractVectorsTest]) checks that its verifier gives
 * every vector the verdict its `expect` states. A change to the contract is a
 * change here, regenerated with `just server contract-vectors`; the file is
 * never edited by hand, and [ContractVectorsTest] reds when it no longer
 * matches what this object would write.
 *
 * ES256 signatures are randomised, so regenerating changes every signature
 * and nothing else. The drift check therefore compares tokens without their
 * signature segment, and verifies the checked-in signatures separately.
 */
object ContractVectors {
    const val ISSUER = "https://hoglake.contract.test"
    const val AUDIENCE = "hoglake"
    const val ISSUED_AT = 1_767_225_600L
    const val VERIFY_AT = ISSUED_AT + 60
    const val PREDICATE_FIELD = "team_id"
    const val BACKEND_ID = "7c9e2a14-3f51-4b8d-9e60-2d5a1f8c44aa"

    /** Where the generator writes, relative to the server project (Gradle's test working directory). */
    const val PATH = "src/test/resources/oauth/contract-vectors.json"

    private const val ORG = "0190a1b2-c3d4-7e5f-8a9b-0c1d2e3f4a5b"
    private const val TENANT_TTL = 15 * 60L
    private const val OPERATOR_TTL = 5 * 60L

    // The fixed test key: d is published on purpose (32 bytes of 0x2a), and
    // x/y are its public point. sign() verifies its own output against the
    // public key, so a typo in either half fails generation.
    private const val KEY_D = "KioqKioqKioqKioqKioqKioqKioqKioqKioqKioqKio"
    private const val KEY_X = "DJAdQjyDHKheJ8c8JjuhMnIbudeoTE8DgLKmdW_WATM"
    private const val KEY_Y = "HIhwI03sh4UEwXQUT6SxS2amUWkWBtgXPlW9N-OBVp4"

    private val mapper = ObjectMapper()
    private val b64 = Base64.getUrlEncoder().withoutPadding()
    private val b64d = Base64.getUrlDecoder()

    private val curve: ECParameterSpec =
        AlgorithmParameters.getInstance("EC").run {
            init(ECGenParameterSpec("secp256r1"))
            getParameterSpec(ECParameterSpec::class.java)
        }
    private val privateKey: ECPrivateKey =
        KeyFactory.getInstance("EC")
            .generatePrivate(ECPrivateKeySpec(BigInteger(1, b64d.decode(KEY_D)), curve)) as ECPrivateKey
    private val publicKey: ECPublicKey =
        KeyFactory.getInstance("EC").generatePublic(
            ECPublicKeySpec(ECPoint(BigInteger(1, b64d.decode(KEY_X)), BigInteger(1, b64d.decode(KEY_Y))), curve),
        ) as ECPublicKey

    /** The RFC 7638 thumbprint of the key, first 8 bytes in hex: stable while the key is. */
    val KID: String =
        MessageDigest.getInstance("SHA-256")
            .digest("""{"crv":"P-256","kty":"EC","x":"$KEY_X","y":"$KEY_Y"}""".toByteArray())
            .take(8)
            .joinToString("") { "%02x".format(it) }

    private val COMMENT =
        listOf(
            "The token contract hoglake verifies (docs/auth.md). hoglake owns this file; every issuer conforms to it.",
            "Generated by: hoglake, server/src/test/kotlin/com/posthog/hoglake/auth/ContractVectors.kt " +
                "(just server contract-vectors). Do not edit by hand.",
            "An issuer conforms by minting each vector's client/operator input at issued_at and matching header " +
                "and claims; hoglake's suite checks every token against its verifier and the vector's expect.",
            "expect is the verdict at verify_at for HOGLAKE_AUTH_ISSUER=issuer, HOGLAKE_AUTH_AUDIENCE=hoglake, " +
                "HOGLAKE_AUTH_PREDICATE_FIELDS=team_id, the default scoped lifetime cap (900s), and the rtg " +
                "backends configured as hoglite.",
            "ES256 signatures are randomised: re-minting gives the same header and claims segments, " +
                "a different signature.",
            "The key is a test constant; test_private_key_d is published on purpose.",
        )

    /** The whole document, freshly signed. */
    fun document(): ObjectNode {
        val root = mapper.createObjectNode()
        root.putArray("comment").apply { COMMENT.forEach { add(it) } }
        root.put("issuer", ISSUER)
        root.put("issued_at", ISSUED_AT)
        root.put("verify_at", VERIFY_AT)
        root.putObject("jwks").putArray("keys").addObject().apply {
            put("kty", "EC")
            put("crv", "P-256")
            put("x", KEY_X)
            put("y", KEY_Y)
            put("use", "sig")
            put("alg", "ES256")
            put("kid", KID)
        }
        root.put("test_private_key_d", KEY_D)
        val vectors = root.putArray("vectors")
        specs().forEach { vectors.add(it.render()) }
        return root
    }

    /** [document] serialized the way the checked-in file is: two-space indent, one array element per line. */
    fun render(document: JsonNode): String {
        val indenter = DefaultIndenter("  ", "\n")
        val printer =
            object : DefaultPrettyPrinter() {
                init {
                    _objectIndenter = indenter
                    _arrayIndenter = indenter
                }

                override fun createInstance(): DefaultPrettyPrinter = this

                override fun writeObjectFieldValueSeparator(g: com.fasterxml.jackson.core.JsonGenerator) {
                    g.writeRaw(": ")
                }
            }
        return mapper.writer(printer).writeValueAsString(document) + "\n"
    }

    /** [document] with every token's signature segment removed: the part regeneration must reproduce. */
    fun withoutSignatures(document: JsonNode): JsonNode {
        val copy = document.deepCopy<JsonNode>()
        (copy["vectors"] as ArrayNode).forEach { vector ->
            val token = vector["token"].asText()
            (vector as ObjectNode).put("token", token.substringBeforeLast('.'))
        }
        return copy
    }

    private fun tenantInput(
        credential: String,
        name: String,
        scope: String,
        delegates: Boolean,
    ): ObjectNode =
        mapper.createObjectNode().apply {
            put("credential_id", credential)
            put("name", name)
            put("org", ORG)
            put("scope", scope)
            put("delegates", delegates)
        }

    private fun placement(): ObjectNode =
        mapper.createObjectNode().apply {
            put("backend_type", "hoglite")
            put("backend_id", BACKEND_ID)
            put("tenant_id", "t_3fa8c1d9e2")
            put("incarnation", 1)
        }

    private fun teams(): ObjectNode =
        mapper.createObjectNode().apply {
            put("42", "write")
            put("7", "read")
        }

    private fun cat(scope: String): ObjectNode = mapper.createObjectNode().apply { putArray(ORG).add(scope) }

    private fun rtg(): ObjectNode =
        mapper.createObjectNode().apply {
            put("b", "hoglite")
            put("be", BACKEND_ID)
            put("t", "t_3fa8c1d9e2_1")
        }

    private fun prd(): ObjectNode = mapper.createObjectNode().apply { set<JsonNode>(PREDICATE_FIELD, teams()) }

    private fun accept(kind: String): ObjectNode =
        mapper.createObjectNode().apply {
            put("verdict", "accept")
            put("kind", kind)
        }

    private fun refuse(reason: String): ObjectNode =
        mapper.createObjectNode().apply {
            put("verdict", "refuse")
            put("reason", reason)
        }

    /** One vector: the issuer-side input, and the claims (in token order) it mints to. */
    private class Spec(
        val name: String,
        val description: String,
        val inputKey: String,
        val input: ObjectNode,
        val jti: Int,
        val expect: ObjectNode,
        val audience: String = AUDIENCE,
        val ttl: Long = TENANT_TTL,
        /** Claims between `jti` and `exp`, in the order the token carries them. */
        val body: List<Pair<String, JsonNode>>,
    ) {
        fun render(): ObjectNode {
            val jtiText = "00000000-0000-4000-8000-%012d".format(jti)
            val claims = linkedMapOf<String, JsonNode>()
            claims["iss"] = mapper.valueToTree(ISSUER)
            claims["aud"] = mapper.valueToTree(audience)
            body.firstOrNull { it.first == "sub" }?.let { claims["sub"] = it.second }
            claims["jti"] = mapper.valueToTree(jtiText)
            body.filter { it.first != "sub" }.forEach { (k, v) -> claims[k] = v }
            claims["exp"] = mapper.valueToTree(ISSUED_AT + ttl)
            claims["iat"] = mapper.valueToTree(ISSUED_AT)
            claims["nbf"] = mapper.valueToTree(ISSUED_AT)
            val header = mapper.createObjectNode().put("alg", "ES256").put("kid", KID).put("typ", "JWT")

            return mapper.createObjectNode().apply {
                put("name", name)
                put("description", description)
                set<JsonNode>(inputKey, input)
                put("audience", audience)
                put("jti", jtiText)
                set<JsonNode>("expect", expect)
                put("token", sign(header, mapper.createObjectNode().setAll<ObjectNode>(claims)))
                set<JsonNode>("header", header)
                // Sorted, for reading; the token carries the minted order.
                set<JsonNode>("claims", mapper.createObjectNode().setAll<ObjectNode>(claims.toSortedMap()))
            }
        }
    }

