package com.posthog.hoglake.auth

import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.node.ObjectNode

/**
 * The generator of `oauth/session-profile-vectors.json`: the session profile
 * (docs/auth.md, "Session profile with embedded storage credentials") written
 * down as signed examples, verified with `HOGLAKE_AUTH_SESSION_PROFILE=on`.
 *
 * A SEPARATE file from `contract-vectors.json`, for two reasons. The main
 * file's verdicts hold under the default configuration, and the profile is
 * off by default: there, one vector pins that such a token is refused as
 * `profile_not_enabled`. And the main file's shape is what issuers' suites
 * decode strictly; this file carries the same shape, so an issuer that wants
 * to conform to the profile reads it the same way, but until one does, every
 * vector here is `mutation`: minted from a `client` input as usual and then
 * changed by adding the profile's claims — no conforming issuer produces it
 * yet. When an issuer implements the profile, the vectors it mints lose their
 * `mutation` and its suite picks them up.
 *
 * The credential strings are fictional; they are not usable keys. Nothing in
 * hoglake reads them: [SessionProfile] checks presence, type and expiry only.
 */
object SessionProfileVectors {
    /** Where the generator writes, relative to the server project (Gradle's test working directory). */
    const val PATH = "src/test/resources/oauth/session-profile-vectors.json"

    private val mapper = ObjectMapper()

    /** The bundle's fictional expiry: 5 minutes past the tenant token's `exp`. */
    const val AWS_EXPIRES_AT = ContractVectors.ISSUED_AT + 15 * 60L + 5 * 60L

    private val COMMENT =
        listOf(
            "The session profile hoglake verifies (docs/auth.md, \"Session profile with embedded storage " +
                "credentials\"). hoglake owns this file; an issuer that mints the profile conforms to it.",
            "Generated by: hoglake, server/src/test/kotlin/com/posthog/hoglake/auth/SessionProfileVectors.kt " +
                "(just server contract-vectors). Do not edit by hand.",
            "expect is the verdict at verify_at for HOGLAKE_AUTH_SESSION_PROFILE=on and otherwise the same " +
                "configuration as contract-vectors.json (issuer, audience hoglake, predicate field team_id, " +
                "rtg backends configured as hoglite).",
            "Every vector is a mutation today: a client input minted as the main file mints it, then the " +
                "profile's claims added. No issuer mints the profile yet; an issuer's suite skips mutations.",
            "aws.* values are fictional. hoglake never uses them, never logs them, and never echoes them in " +
                "a refusal; it checks presence, type and that exp <= aws.expires_at (<= session_deadline).",
            "ES256 signatures are randomised: re-minting gives the same header and claims segments, " +
                "a different signature.",
        )

    private fun text(v: String): JsonNode = mapper.valueToTree(v)

    private fun aws(expiresAt: Long = AWS_EXPIRES_AT): ObjectNode =
        mapper.createObjectNode().apply {
            put("access_key_id", "FICTIONAL_ACCESS_KEY_ID")
            put("secret_access_key", "FICTIONAL_SECRET_ACCESS_KEY")
            put("session_token", "FICTIONAL_SESSION_TOKEN")
            put("region", "us-east-1")
            put("expires_at", expiresAt)
        }

    private fun remoteSchemas(vararg entries: Pair<String, List<String>>): ObjectNode =
        mapper.createObjectNode().apply {
            entries.forEach { (name, scopes) -> putArray(name).apply { scopes.forEach { add(it) } } }
        }

    /**
     * [body] (the metadata claims a token kind carries) with the profile's
     * claims appended: the marker triple, `primary_catalog` equal to the one
     * `cat` key, two read-only remote schemas, and a fictional bundle. The
     * main file's disabled-profile vector uses it too, so both files describe
     * the same token.
     */
    internal fun profileBody(
        body: List<Pair<String, JsonNode>>,
        primaryCatalog: String = ContractVectors.ORG,
        remote: ObjectNode = remoteSchemas("shared" to listOf("read"), "imports" to listOf("read")),
        bundle: ObjectNode = aws(),
        withMarker: Boolean = true,
        version: Long = SessionProfile.VERSION,
    ): List<Pair<String, JsonNode>> =
        body +
            (
                if (withMarker) {
                    listOf(
                        "profile" to text(SessionProfile.ID),
                        "version" to mapper.valueToTree<JsonNode>(version),
                        "purpose" to text(SessionProfile.PURPOSE),
                    )
                } else {
                    emptyList()
                }
            ) +
            listOf(
                "primary_catalog" to text(primaryCatalog),
                "remote_schemas" to remote,
                "aws" to bundle,
            )

    fun document(): ObjectNode {
        val root = mapper.createObjectNode()
        root.putArray("comment").apply { COMMENT.forEach { add(it) } }
        root.put("issuer", ContractVectors.ISSUER)
        root.put("issued_at", ContractVectors.ISSUED_AT)
        root.put("verify_at", ContractVectors.VERIFY_AT)
        root.putObject("config").put("session_profile", "on")
        root.putObject("jwks").putArray("keys").add(ContractVectors.jwk())
        root.put("test_private_key_d", ContractVectors.TEST_PRIVATE_KEY_D)
        val vectors = root.putArray("vectors")
        specs().forEach { vectors.add(it.render()) }
        return root
    }

    private fun specs(): List<ContractVectors.Spec> {
        val reader = "hlc_0123456789abcdef01234567"
        val team = "hlc_00112233445566778899aabb"
        val owner = "0190a1b2-c3d4-7e5f-8a9b-000000000042"
        val org = ContractVectors.ORG
        val readerInput = { ContractVectors.tenantInput(reader, "pyhoglake-reader", "read", false) }
        val scopedInput = {
            ContractVectors.tenantInput(team, "laptop", "write", false).apply {
                put("owner_user_uuid", owner)
                set<JsonNode>("teams", ContractVectors.teams())
            }
        }
        val tenantBody =
            listOf(
                "sub" to text(reader),
                "ten" to text("tenant"),
                "org" to text(org),
                "cat" to ContractVectors.cat("read"),
                "cli" to text("pyhoglake-reader"),
            )
        val scopedBody =
            listOf(
                "sub" to text(team),
                "ten" to text("scoped"),
                "org" to text(org),
                "cat" to ContractVectors.cat("write"),
                "prd" to ContractVectors.prd(),
                "cli" to text("laptop"),
                "usr" to text(owner),
            )
        val added = "profile, version, purpose, primary_catalog, remote_schemas and a fictional aws object are added"
        return listOf(
            ContractVectors.Spec(
                "session_tenant",
                "A tenant token carrying the profile: accepted; the caller's remote schemas are the read-only " +
                    "names it lists, and hoglake never reads aws.*.",
                "client",
                readerInput(),
                101,
                ContractVectors.accept("tenant"),
                mutation = added,
                body = profileBody(tenantBody),
            ),
            ContractVectors.Spec(
                "session_scoped_routed",
                "A scoped, routed token carrying the profile: prd and rtg apply as always; primary_catalog is " +
                    "the routed catalog.",
                "client",
                scopedInput().apply { set<JsonNode>("placement", ContractVectors.placement()) },
                102,
                ContractVectors.accept("scoped"),
                mutation = added,
                body = profileBody(scopedBody + listOf("rtg" to ContractVectors.rtg())),
            ),
            ContractVectors.Spec(
                "session_exp_after_aws_expiry",
                "The token outlives its credentials: exp is later than aws.expires_at, so it is refused.",
                "client",
                readerInput(),
                103,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                mutation = "$added; aws.expires_at is one second before exp",
                body = profileBody(tenantBody, bundle = aws(ContractVectors.ISSUED_AT + 15 * 60L - 1)),
            ),
            ContractVectors.Spec(
                "session_remote_schema_write",
                "A remote schema granted write: remote schemas are read-only by construction, so it is refused.",
                "client",
                readerInput(),
                104,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                mutation = "$added; remote_schemas.shared is [\"read\", \"write\"]",
                body = profileBody(tenantBody, remote = remoteSchemas("shared" to listOf("read", "write"))),
            ),
            ContractVectors.Spec(
                "session_primary_catalog_mismatch",
                "primary_catalog names a catalog cat does not: refused.",
                "client",
                readerInput(),
                105,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                mutation = "$added; primary_catalog is another catalog name",
                body = profileBody(tenantBody, primaryCatalog = "another-catalog"),
            ),
            ContractVectors.Spec(
                "session_bundle_without_marker",
                "A credential object without the profile marker: a token nobody declared the meaning of, refused.",
                "client",
                readerInput(),
                106,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                mutation = "primary_catalog, remote_schemas and a fictional aws object are added without profile",
                body = profileBody(tenantBody, withMarker = false),
            ),
            ContractVectors.Spec(
                "session_unknown_version",
                "A profile version this verifier does not know: refused, never parsed as the version it knows.",
                "client",
                readerInput(),
                107,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                mutation = "$added; version is 2",
                body = profileBody(tenantBody, version = 2),
            ),
            ContractVectors.Spec(
                "session_operator",
                "An operator token carrying the profile: a user session is never fleet authority, refused.",
                "operator",
                mapper.createObjectNode().apply {
                    put("subject", "issuer:provisioner")
                    put("client", "provisioner")
                },
                108,
                ContractVectors.refuse(JwtViolation.MALFORMED),
                ttl = 5 * 60L,
                mutation = added,
                body =
                    profileBody(
                        listOf(
                            "sub" to text("issuer:provisioner"),
                            "ten" to text("operator"),
                            "cli" to text("provisioner"),
                        ),
                    ),
            ),
        )
    }
}
