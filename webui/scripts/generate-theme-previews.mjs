import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const output = new URL("docs/themes/", root);
const css = await readFile(new URL("src/color-themes.css", root), "utf8");
const palettes = [...css.matchAll(
  /:root\[data-color-theme="([a-z0-9-]+)"\](:not\(\[data-theme="light"\]\)|\[data-theme="light"\])\s*\{([^}]+)\}/g,
)];
if (palettes.length === 0) throw new Error("No theme palettes found.");
await mkdir(output, { recursive: true });

for (const [, name, selector, block] of palettes) {
  const mode = selector.startsWith(":not") ? "dark" : "light";
  const colors = Object.fromEntries(
    [...block.matchAll(/--([a-z-]+):\s*(#[a-f\d]{6});/g)]
      .map(([, token, value]) => [token, value]),
  );
  const color = (token) => {
    if (!colors[token]) throw new Error(`Missing ${token} in ${name}/${mode}.`);
    return colors[token];
  };
  const svg = `<!-- Generated by npm run docs:themes from src/color-themes.css. -->
<svg xmlns="http://www.w3.org/2000/svg" width="220" height="72" viewBox="0 0 220 72" role="img" aria-labelledby="title description">
  <title id="title">${name} ${mode} palette</title>
  <desc id="description">Background ${color("bg")}, text ${color("text")}, accent ${color("accent")}, success ${color("ok")}, warning ${color("warn")}, error ${color("bad")}.</desc>
  <rect x="0.5" y="0.5" width="219" height="71" rx="6" fill="${color("bg")}" stroke="${color("border")}"/>
  <rect x="1" y="1" width="218" height="34" rx="5" fill="${color("bg-raised")}"/>
  <rect x="8" y="1" width="204" height="3" rx="1.5" fill="${color("accent")}"/>
  <g font-family="-apple-system, BlinkMacSystemFont, Segoe UI, Arial, sans-serif">
    <text x="12" y="27" font-size="19" font-weight="600" fill="${color("text")}">Aa</text>
    <text x="45" y="25" font-size="12" fill="${color("text-dim")}">Muted</text>
    <text x="109" y="25" font-size="12" fill="${color("accent")}">Link</text>
    <rect x="151" y="10" width="57" height="21" rx="3" fill="${color("accent")}"/>
    <text x="179.5" y="24" text-anchor="middle" font-size="11" fill="${color("accent-contrast")}">Button</text>
    <circle cx="17" cy="53" r="4" fill="${color("ok")}"/>
    <text x="27" y="57" font-size="11" fill="${color("ok")}">OK</text>
    <circle cx="80" cy="53" r="4" fill="${color("warn")}"/>
    <text x="90" y="57" font-size="11" fill="${color("warn")}">Warning</text>
    <circle cx="162" cy="53" r="4" fill="${color("bad")}"/>
    <text x="172" y="57" font-size="11" fill="${color("bad")}">Error</text>
  </g>
</svg>
`;
  await writeFile(new URL(`${name}-${mode}.svg`, output), svg);
}

console.log(`Generated ${palettes.length} theme previews.`);
